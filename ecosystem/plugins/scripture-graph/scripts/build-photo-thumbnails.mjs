import { readFileSync, writeFileSync, mkdirSync } from 'node:fs';
import sharp from 'sharp';
import { fileURLToPath } from 'node:url';
const catalog = JSON.parse(readFileSync(new URL('../scene-release/catalog.json', import.meta.url), 'utf8'));
const folder = new URL('../src/assets/photo-thumbnails/', import.meta.url);
mkdirSync(folder, { recursive: true });
let bytes = 0;
for (const [id, row] of Object.entries(catalog)) {
  const thumb = await sharp(fileURLToPath(new URL('../scene-release/' + row.portrait.file, import.meta.url)))
    .resize(320, 400, { fit: 'inside', withoutEnlargement: true }).jpeg({ quality: 65, mozjpeg: true }).toBuffer();
  writeFileSync(new URL(id + '.jpg', folder), thumb); bytes += thumb.length;
}
const ids = Object.keys(catalog).sort();
writeFileSync(new URL('../src/study/photoThumbnails.ts', import.meta.url), '// Generated by scripts/build-photo-thumbnails.mjs. Exact artwork, including offline.\n'
  + ids.map((id, i) => `import p${i} from '../assets/photo-thumbnails/${id}.jpg';`).join('\n')
  + '\nexport const PHOTO_THUMBNAILS: Record<string, string> = {\n'
  + ids.map((id, i) => `  '${id}': p${i},`).join('\n') + '\n};\n');
// A dedicated Library cover, derived from the existing Emmaus artwork.
writeFileSync(new URL('../src/assets/library-covers/photos.jpg', import.meta.url),
  await sharp(fileURLToPath(new URL('../scene-release/' + catalog['emmaus-road'].portrait.file, import.meta.url)))
    .resize(320, 400, { fit: 'cover' }).jpeg({ quality: 75, mozjpeg: true }).toBuffer());
console.log(`${ids.length} unique offline thumbnails, ${bytes} bytes`);
