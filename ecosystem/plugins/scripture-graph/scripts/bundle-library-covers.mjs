import { readdirSync, readFileSync, writeFileSync, mkdirSync, copyFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';

const assets = new URL('../src/assets/library-covers/', import.meta.url);

// Refresh intentionally from the authored UI artwork, never the reading library.
// Normal builds use checked-in assets and do not require a personal vault.
export function bundleLibraryCovers(refresh = false) {
  if (refresh) {
    const source = new URL('../../../../Scripture%20Graph/AI%20Library/00%20System/covers/', import.meta.url);
    mkdirSync(assets, { recursive: true });
    for (const name of readdirSync(source).filter(name => /\.jpg$/.test(name) || name === 'CREDITS.md')) {
      copyFileSync(new URL(name, source), new URL(name, assets));
    }
  }
  const names = readdirSync(assets).filter(name => name.endsWith('.jpg')).sort();
  if (!names.length) throw new Error('Missing bundled library artwork');
  for (const name of names) {
    if (!/^[a-z0-9-]+\.jpg$/.test(name)) throw new Error(`Invalid cover filename: ${name}`);
    if (readFileSync(new URL(name, assets)).subarray(0, 3).toString('hex') !== 'ffd8ff') {
      throw new Error(`Invalid JPEG: ${name}`);
    }
  }
  const code = '// Generated by scripts/bundle-library-covers.mjs. All tile art works without vault sync.\n'
    + names.map((name, i) => `import cover${i} from './library-covers/${name}';`).join('\n')
    + '\nexport const BUNDLED_COVERS: Record<string, string> = {\n'
    + names.map((name, i) => `  '${name.slice(0, -4)}': cover${i},`).join('\n')
    + "\n};\nBUNDLED_COVERS['my-work'] ??= BUNDLED_COVERS.scholarship!;\nBUNDLED_COVERS.scriptures ??= BUNDLED_COVERS.bible!;\n";
  writeFileSync(new URL('../src/assets/covers.ts', import.meta.url), code);
  return names.length;
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  console.log(`Bundled ${bundleLibraryCovers(process.argv.includes('--refresh'))} library covers`);
}
